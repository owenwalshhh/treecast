import { chromium } from "playwright";
const DIR = process.env.SHOT_DIR || "/tmp";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1360, height: 860 } });
const errors = [];
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
page.on("pageerror", (e) => errors.push(String(e)));
await page.goto("http://127.0.0.1:5173/", { waitUntil: "domcontentloaded" });
await page.waitForTimeout(2500);
await page.getByRole("button", { name: /^Optimize$/ }).click();
await page.waitForTimeout(2000);
await page.screenshot({ path: `${DIR}/ui-y0.png` });
// Open Growth and drag the year slider to 30.
await page.getByRole("button", { name: /Growth/ }).first().click();
await page.waitForTimeout(250);
const slider = page.locator('input[type="range"]').last();
await slider.focus();
for (let i = 0; i < 30; i++) await page.keyboard.press("ArrowRight");
await page.waitForTimeout(900);
await page.screenshot({ path: `${DIR}/ui-y30.png` });
console.log("ERRORS:" + JSON.stringify(errors));
await browser.close();
